-- 158: two ordering defects in get_session_queue, found in the same
-- red-team pass that found 157's NULL-poisoning landmine. Layered on top
-- of 157 (same CREATE OR REPLACE target), not folded into it, so each
-- fix stays independently reviewable and independently revertable -- see
-- 157's own header for why that file was kept to one change only.
--
-- DEFECT 1 -- THE 4x WINDOW HAS NO ORDER BY. `due`'s CTE computes its
-- window functions (`row_number() over (partition by s.id order by
-- due_at)`, `row_number() over (order by due_at)`) and THEN applies
-- `limit greatest(p_limit_due, 1) * 4` with no ORDER BY of its own.
-- Postgres evaluates window functions before LIMIT, but LIMIT with no
-- ORDER BY does not promise it keeps any PARTICULAR 4N rows -- it keeps
-- whatever the underlying scan happens to produce first (in practice,
-- something close to insertion/physical order, which is not "the 4N most
-- due"). On a deck where more than `p_limit_due * 4` cards are overdue at
-- once, this can silently retain a mix of far-future-due and long-overdue
-- rows instead of the ones that are actually most due, and the window
-- ranks (`source_rank`/`overall_rank`) computed over that arbitrary subset
-- are then wrong in a way nothing downstream can detect.
--
-- NOT OBSERVED ON PRODUCTION -- checked, not assumed: today's maximum
-- due-now count across all 19 real users is 5 (`select max(n) from
-- (select count(*) n from card_states where state <> 'new' and due_at <=
-- now() group by user_id) x`), and the smallest real p_limit_due this
-- function is ever called with makes `p_limit_due * 4` comfortably larger
-- than that. It is a real defect and a straightforward fix, so it is fixed
-- here rather than left for the day a deck's overdue count actually
-- crosses that line -- not a response to an observed failure.
--
-- FIX: `order by cs.due_at asc` added to the `due` CTE, directly before its
-- LIMIT. The LIMIT itself is kept, deliberately -- it exists to bound the
-- cost of the two window functions on a large deck, and removing it instead
-- of ordering it would trade a correctness bug for a performance one on
-- exactly the large-deck case this function needs to stay cheap for.
--
-- DEFECT 2 -- THE NEW-CARD TIEBREAK IS NOT MEANINGFUL. `new_cards` orders
-- by `cs.card_id`, a random uuid: arbitrary but STABLE today, because every
-- new_cards row is card-backed and `cs.card_id` is never null in that
-- population, so the ordering is at least consistent run to run. The
-- moment a question-backed new_cards row exists (question_id set, card_id
-- NULL -- structurally possible since 127, and the literal next migration
-- in this batch starts producing such rows), ordering by `cs.card_id`
-- degrades: every question row's sort key is NULL, so (Postgres's default
-- NULLS LAST for ASC) the entire question population sorts as a single
-- block AFTER every card, in whatever order the scan happens to produce
-- them -- not merely "arbitrary", but arbitrary AND clustered by item kind
-- rather than by anything resembling priority.
--
-- FIX: order by `cs.id` instead -- the surrogate PK 111 added, generated by
-- `gen_random_uuid()` for every card_states row regardless of which item it
-- backs. This restores exactly the pre-existing property ("arbitrary but
-- stable, one flat id space") for the combined card+question population,
-- rather than inventing a real prioritisation scheme -- which is a product
-- decision (what should a fresh account see first?) outside this fix's
-- scope, flagged separately, not decided here.
--
-- SCOPE: as with 157, every line NOT called out above is reproduced
-- verbatim from 157's own body (itself reproduced verbatim from the
-- deployed 126 function plus 157's single change) -- no other behaviour
-- moves. Proven no-op for books: see this migration's own exit test
-- (BEGIN;...ROLLBACK; against production), reported alongside this file.
--
-- Transaction control is the RUNNER's -- no begin/commit in this file.

CREATE OR REPLACE FUNCTION public.get_session_queue(p_limit_due integer, p_limit_new integer)
 RETURNS TABLE(card_id uuid, book_id uuid, queue_position integer, reason text)
 LANGUAGE plpgsql
AS $function$
#variable_conflict use_column
declare
  caller uuid := auth.uid();
begin
  if caller is null then
    raise exception 'get_session_queue: no authenticated user';
  end if;

  return query
  with due as (
    select cs.id as state_id, cs.card_id, cs.book_id, cs.due_at, cs.stability,
           row_number() over (partition by s.id order by cs.due_at asc) as source_rank,
           row_number() over (order by cs.due_at asc) as overall_rank
    from public.card_states cs
    join public.sources s on s.book_id = cs.book_id and s.kind = 'book'
    join public.books bk on bk.id = cs.book_id and bk.deleted_at is null
    join public.cards c on c.user_id = cs.user_id and c.id = cs.card_id
                       and c.suspended_at is null
    where cs.user_id = caller and cs.state <> 'new' and cs.due_at <= now()
    -- 158: ORDER BY before the LIMIT -- without it, LIMIT is free to keep
    -- ANY 4N rows once the true count exceeds p_limit_due*4, not the 4N
    -- most-due ones the window functions below assume they're ranking.
    order by cs.due_at asc
    limit greatest(p_limit_due, 1) * 4
  ),
  warm_up as (
    select state_id, card_id, book_id, 0::int as queue_position, 'warm_up'::text as reason
    from due
    order by stability desc nulls last, due_at asc
    limit 1
  ),
  due_interleaved as (
    select card_id, book_id,
           (row_number() over (order by source_rank asc, overall_rank asc))::int as queue_position,
           'due'::text as reason
    from due
    where not exists (
      select 1 from warm_up w where w.state_id = due.state_id
    )
    limit greatest(p_limit_due - 1, 0)
  ),
  new_cards as (
    select cs.card_id, cs.book_id,
           -- 158: cs.id, not cs.card_id -- see header. Stable across a
           -- mixed card+question population; cs.card_id is NULL for a
           -- question-backed row and would sort the entire question
           -- population into one arbitrary block.
           (row_number() over (order by cs.id))::int as queue_position,
           'new'::text as reason
    from public.card_states cs
    join public.books bk on bk.id = cs.book_id and bk.deleted_at is null
    join public.cards c on c.user_id = cs.user_id and c.id = cs.card_id
                       and c.suspended_at is null
    where cs.user_id = caller and cs.state = 'new'
    limit greatest(p_limit_new, 0)
  )
  select card_id, book_id, queue_position, reason from warm_up
  union all
  select card_id, book_id, queue_position + 1, reason from due_interleaved
  union all
  select card_id, book_id, queue_position + 1000, reason from new_cards
  order by queue_position asc;
end;
$function$
;
